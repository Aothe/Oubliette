#!/usr/bin/env node
// Writes src/sin-table.ts: 1,024 entries of sin(2*pi*i/1024) in Q14, built from one quarter wave
// and mirrored so the symmetries are exact (sin(a) = -sin(a + 512), sin(256) = 16384). The float
// routine runs here, once, on the machine that commits the file; the simulation reads the literal.
//   node proto/loop/tools/gen-sin.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const N = 1024, Q = 16384, q = [];
for (let i = 0; i <= N / 4; i++) q.push(Math.round(Math.sin((2 * Math.PI * i) / N) * Q));
q[0] = 0; q[N / 4] = Q;
const full = new Array(N);
for (let i = 0; i <= N / 4; i++) { full[i] = q[i]; full[N / 2 - i] = q[i]; full[N / 2 + i] = -q[i]; full[(N - i) % N] = -q[i]; }
full[0] = 0; full[N / 2] = 0;
const lines = [];
for (let i = 0; i < N; i += 16) lines.push("  " + full.slice(i, i + 16).join(", ") + ",");
const src = `// Generated by tools/gen-sin.mjs — do not edit. sin(2*pi*i/1024) in Q14 (16384 = 1).
export const SIN_Q14: readonly number[] = [
${lines.join("\n")}
];
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "sin-table.ts"), src);
console.log("wrote src/sin-table.ts:", N, "entries");
